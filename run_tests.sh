    echo ""
    echo "Usage: ./run_tests.sh [basic|validate|all]"
    echo ""
    echo "Modes:"
    echo "  basic     - Run basic test suite (test/runtests.jl)"
    echo "  validate  - Run comprehensive model validation (test/validate_all_models.jl)"
    echo "  all       - Run both (default)"
